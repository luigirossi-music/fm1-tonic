"""The factory preset bank: up to 8 TNP1 presets (firmware/src/app/tnp.h) as C arrays the firmware loads.
   gen_preset_bank.py OUT.h [DIR_OR_FILES...]   (files taken in name order: 01_x.tnp is slot 1; no input = an empty bank)
   gen_preset_bank.py --start OUT.h [FILE.tnp]  (the STARTING POINT: the project a new or reset unit begins with; none = the plain empty one)"""
import os, sys
if sys.argv[1] == '--start':
    out, src = sys.argv[2], sys.argv[3:]
    b = open(src[0], 'rb').read() if src else b''
    if b and b[:4] != b'TNP1':
        sys.exit('%s is not a TNP1 preset' % src[0])
    open(out, 'w').write('/* generated by tools/gen_preset_bank.py --start */\n#define TONIC_START_N %d\nstatic const uint8_t TNS[%d] = {%s};\n' %
                          (1 if b else 0, max(1, len(b)), ','.join(str(x) for x in b) or '0'))
    sys.exit(0)
out, srcs = sys.argv[1], sys.argv[2:]
files = []
for s in srcs:
    files += sorted(os.path.join(s, f) for f in os.listdir(s) if f.endswith('.tnp')) if os.path.isdir(s) else [s]
if len(files) > 8:
    sys.exit('preset bank: at most 8 factory presets (%d given)' % len(files))
o = ['/* generated by tools/gen_preset_bank.py: the factory Tonic presets */']
for i, f in enumerate(files):
    b = open(f, 'rb').read()
    if b[:4] != b'TNP1':
        sys.exit('%s is not a TNP1 preset' % f)
    o.append('static const uint8_t TNB_%d[%d] = {%s};' % (i, len(b), ','.join(str(x) for x in b)))
o.append('#define TONIC_BANK_N %d' % len(files))
o.append('static const struct { const uint8_t *p; uint16_t n; } TONIC_BANK[%d] = {%s};' %
         (max(1, len(files)), ','.join('{TNB_%d,sizeof TNB_%d}' % (i, i) for i in range(len(files))) or '{0,0}'))
open(out, 'w').write('\n'.join(o) + '\n')
